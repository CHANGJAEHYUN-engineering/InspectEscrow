"use strict";
const fs=require("node:fs"),path=require("node:path");
const {candidateTerms}=require("./new-trade-endpoints.cjs");
const {KNOWN_TRADES,documentApproval,policyVerification,nextActions,milestones}=require("./trade-workspace-endpoints.cjs");
const assert=(v,m)=>{if(!v)throw Error(m);};
const candidate=KNOWN_TRADES.find(x=>x.preferred);
assert(candidate,"candidate missing");
const approval=documentApproval(candidate.policy);
assert(approval.status==="DRAFT_MODEL_B_NOT_APPROVED_FOR_ONCHAIN","draft status was rewritten");
assert(approval.approved===false,"draft must not be approved");
const policy=policyVerification(candidate,candidateTerms,1);
assert(policy.immutableHash.verified,"candidate policy hash not reproducible");
assert(policy.statusConflict===true,"draft/onchain conflict not exposed");
assert(policy.onchainLifecycle.stateName==="PROPOSED","onchain state mislabeled");
const actions=nextActions(1,{attempt:0},{attempt:0},[0,"0x"],false);
assert(actions.length===2&&actions.every(x=>x.route==="/#roles"),"PROPOSED next actions wrong");
const steps=milestones(1,{attempt:0},{attempt:0},false);
assert(steps.find(x=>x.id==="proposal").status==="DONE","proposal milestone wrong");
assert(steps.find(x=>x.id==="policy").status==="PENDING","policy milestone wrong");
const html=fs.readFileSync(path.join(__dirname,"trades.html"),"utf8");
const js=fs.readFileSync(path.join(__dirname,"trades.js"),"utf8");
const server=fs.readFileSync(path.join(__dirname,"server.cjs"),"utf8");
const endpoint=fs.readFileSync(path.join(__dirname,"trade-workspace-endpoints.cjs"),"utf8");
for(const token of ["trade-list","detail","READ ONLY"])assert(html.includes(token),"html missing "+token);
for(const token of ["/api/trades","policyDocumentStatus","serverTransactionsSent:0"])assert(server.includes(token)||js.includes(token)||endpoint.includes(token),"route/ui missing "+token);
assert(!/eth_requestAccounts|signTypedData|sendTransaction/.test(js),"read-only trade page requests wallet action");
console.log(JSON.stringify({allPass:true,checks:14,policyDocumentStatus:approval.status,onchainLifecycle:"PROPOSED",hashVerified:policy.immutableHash.verified,transactionsSent:0},null,2));
